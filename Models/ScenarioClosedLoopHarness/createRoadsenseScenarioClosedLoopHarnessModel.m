function addRate(system,name,outSampleTime,position)
add_block("simulink/Signal Attributes/Rate Transition",system+"/"+name, ...
    "Position",position,"OutPortSampleTime",outSampleTime);
end

function wire(system,source,destination,name)
line=add_line(system,source,destination,"autorouting","on");
if strlength(name)>0; set_param(line,"Name",name); end
end

function ensureHarnessModels(root)
required=[ ...
    "ScenarioLibrary/Roadsense_ScenarioLibrary.slx", ...
    "ScenarioSensorSource/Roadsense_ScenarioSensorSource.slx", ...
    "ScenarioAdapters/Roadsense_ScenarioAdapters.slx"];
generators=["createRoadsenseScenarioLibraryModel", ...
    "createRoadsenseScenarioSensorSourceModel", ...
    "createRoadsenseScenarioAdaptersModel"];
for index=1:numel(required)
    if ~isfile(fullfile(root,"Models",required(index))); feval(generators(index)); end
end
integrationPath=fullfile(root,"Models","ClosedLoopIntegration", ...
    "Roadsense_ClosedLoopIntegration.slx");
regenerate=~isfile(integrationPath);
if ~regenerate
    load_system(integrationPath);
    regenerate=numel(find_system("Roadsense_ClosedLoopIntegration", ...
        "SearchDepth",1,"BlockType","Outport"))~=11;
    close_system("Roadsense_ClosedLoopIntegration",0);
end
if regenerate; createRoadsenseClosedLoopIntegrationModel(); end
end

function closeIfLoaded(modelName)
if bdIsLoaded(modelName); close_system(modelName,0); end
end
