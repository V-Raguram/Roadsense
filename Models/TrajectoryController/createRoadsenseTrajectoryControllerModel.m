function modelPath=createRoadsenseTrajectoryControllerModel()
%CREATEROADSENSETRAJECTORYCONTROLLERMODEL Generate closed-loop controller block.
componentDir=fileparts(mfilename("fullpath")); root=fileparts(fileparts(componentDir));
modelName="Roadsense_TrajectoryController";
modelPath=fullfile(componentDir,modelName+".slx");
addpath(fullfile(root,"Models","SharedData")); addpath(componentDir); addpath(fullfile(root,"Data"));
createRoadsenseDataDictionary(fullfile(root,"Data","Roadsense_Data.sldd"));
if bdIsLoaded(modelName); close_system(modelName,0); end
if isfile(modelPath); delete(modelPath); end
new_system(modelName,"Model"); cleanup=onCleanup(@() closeIfLoaded(modelName));
set_param(modelName,"DataDictionary","Roadsense_Data.sldd","SolverType","Fixed-step", ...
    "Solver","FixedStepDiscrete","FixedStep","RsTsBase","StopTime","1.0","SignalLogging","on");

names=["EgoState","LocalPlan","PlannerStatus"];
types=["Bus: RsEgoStateBus","Bus: RsLocalPlanBus","Bus: RsPlannerStatusBus"];
for index=1:3
    y=145+(index-1)*95;
    add_block("simulink/Ports & Subsystems/In1",modelName+"/"+names(index), ...
        "Position",[25 y 55 y+20],"Port",string(index),"OutDataTypeStr",types(index), ...
        "PortDimensions","1","SampleTime","RsTsControl");
end

controller=modelName+"/Closed Loop Trajectory Tracking";
add_block("simulink/User-Defined Functions/MATLAB System",controller, ...
    "Position",[180 105 490 405]);
set_param(controller,"System","RoadsenseTrajectoryControllerSystem", ...
    "MaxPlanPoints","double(RsMaxPlanPoints)","SampleTime","RsTsControl", ...
    "Wheelbase","RsControllerWheelbase","LateralGain","RsControllerLateralGain", ...
    "HeadingGain","RsControllerHeadingGain","SofteningSpeed","RsControllerSofteningSpeed", ...
    "SpeedKp","RsControllerSpeedKp","SpeedKi","RsControllerSpeedKi", ...
    "IntegralLimit","RsControllerIntegralLimit", ...
    "MaximumSteering","RsControllerMaximumSteering", ...
    "MaximumSteeringRate","RsControllerMaximumSteeringRate", ...
    "MaximumAcceleration","RsControllerMaximumAcceleration", ...
    "MaximumDeceleration","RsControllerMaximumDeceleration", ...
    "AccelerationSlew","RsControllerAccelerationSlew", ...
    "PreviewTime","RsControllerPreviewTime","PlanGrace","RsControllerPlanGrace");
for index=1:3
    line=add_line(modelName,names(index)+"/1","Closed Loop Trajectory Tracking/"+index, ...
        "autorouting","on"); set_param(line,"Name",names(index));
end

add_block("simulink/Signal Routing/Bus Creator",modelName+"/Vehicle Control Bus", ...
    "Position",[615 75 625 315],"Inputs","10","OutDataTypeStr","Bus: RsVehicleControlBus");
controlNames=["Timestamp","PlanID","SteeringAngle","SteeringRate", ...
    "AccelerationCommand","Throttle","Brake","TargetSpeed","EmergencyStop","Valid"];
for port=1:10
    line=add_line(modelName,"Closed Loop Trajectory Tracking/"+port, ...
        "Vehicle Control Bus/"+port,"autorouting","on"); set_param(line,"Name",controlNames(port));
end

add_block("simulink/Signal Routing/Bus Creator",modelName+"/Tracking Status Bus", ...
    "Position",[615 345 625 610],"Inputs","12","OutDataTypeStr","Bus: RsTrackingStatusBus");
statusNames=["Timestamp","PlanID","ReferenceIndex","CrossTrackError", ...
    "HeadingError","SpeedError","ReferenceCurvature","ReferenceAge", ...
    "SteeringSaturated","AccelerationSaturated","PlanExpired","Valid"];
for port=1:12
    sourcePort=port+10;
    line=add_line(modelName,"Closed Loop Trajectory Tracking/"+sourcePort, ...
        "Tracking Status Bus/"+port,"autorouting","on"); set_param(line,"Name",statusNames(port));
end

add_block("simulink/Ports & Subsystems/Out1",modelName+"/VehicleControl", ...
    "Position",[740 185 770 205],"OutDataTypeStr","Bus: RsVehicleControlBus");
add_block("simulink/Ports & Subsystems/Out1",modelName+"/TrackingStatus", ...
    "Position",[740 465 770 485],"Port","2","OutDataTypeStr","Bus: RsTrackingStatusBus");
add_line(modelName,"Vehicle Control Bus/1","VehicleControl/1","autorouting","on");
add_line(modelName,"Tracking Status Bus/1","TrackingStatus/1","autorouting","on");

annotation=Simulink.Annotation(modelName,"Roadsense Trajectory Controller"+newline+ ...
    "time/spatial reference selection -> curvature feed-forward + Stanley feedback"+newline+ ...
    "acceleration feed-forward + anti-windup PI -> actuator and slew limits -> fail-safe brake");
annotation.Position=[150 20 760 75];
save_system(modelName,modelPath); clear cleanup; close_system(modelName,0);
fprintf("Generated %s\n",modelPath);
end

function closeIfLoaded(modelName)
if bdIsLoaded(modelName); close_system(modelName,0); end
end
